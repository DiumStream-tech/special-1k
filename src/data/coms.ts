function generateRandomComs(count: number): string[] {
  const prefixes = [
    'Super', 'Ultra', 'Mega', 'Hyper', 'Dark', 'Light', 'Neon', 'Cyber', 'Pixel', 'Retro',
    'Alpha', 'Beta', 'Omega', 'Turbo', 'Nitro', 'Storm', 'Shadow', 'Fire', 'Ice', 'Thunder',
    'Cosmic', 'Void', 'Nova', 'Astro', 'Quantum', 'King', 'Queen', 'Mad', 'Crazy', 'Silent',
    'Wild', 'Free', 'Lost', 'Fast', 'Big', 'Hot', 'Cold', 'Sweet', 'Spicy', 'Salty',
    'Ancient', 'Modern', 'Future', 'Virtual', 'Real', 'True', 'Happy', 'Sad', 'Angry', 'Calm',
    'Red', 'Blue', 'Green', 'Gold', 'Silver', 'Purple', 'Pink', 'Black', 'White', 'Gray',
    'Tiny', 'Giant', 'Brave', 'Bold', 'Swift', 'Lucky', 'Fierce', 'Gentle', 'Clever', 'Wise',
  ]
  const roots = [
    'Gamer', 'Player', 'Master', 'Hunter', 'Knight', 'Ninja', 'Pilot', 'Warrior', 'Wizard', 'Ranger',
    'Sniper', 'Racer', 'Slayer', 'Keeper', 'Runner', 'Fighter', 'Legend', 'Champion', 'Hero', 'Pro',
    'Wolf', 'Fox', 'Bear', 'Eagle', 'Hawk', 'Lion', 'Tiger', 'Dragon', 'Phoenix', 'Falcon',
    'Raven', 'Cobra', 'Panther', 'Lynx', 'Owl', 'Shark', 'Whale', 'Rabbit', 'Deer', 'Bull',
    'Cat', 'Dog', 'Bird', 'Fish', 'Geek', 'Nerd', 'Tech', 'Code', 'Pixel', 'Vibe',
    'Star', 'Moon', 'Sun', 'Sky', 'Cloud', 'Wind', 'Rain', 'Snow', 'Leaf', 'Stone',
  ]
  const suffixes = [
    '', 'YT', 'TV', 'FR', 'X', 'Pro', 'HD', 'Gaming', 'Official', 'Live',
    'Studios', 'Play', 'Craft', 'Tech', 'Code', 'Dev', 'Zone', 'World', 'Land', 'Verse',
    'Space', 'Core', 'Hub', 'Net', 'Box', 'Lab', 'Kit', 'Fan', 'Cult', 'Crew',
  ]

  const seen = new Set<string>()
  const names: string[] = []
  while (names.length < count) {
    const p = prefixes[Math.floor(Math.random() * prefixes.length)]
    const r = roots[Math.floor(Math.random() * roots.length)]
    const s = suffixes[Math.floor(Math.random() * suffixes.length)]
    const n = Math.floor(Math.random() * 9999)
    const name = `${p}${r}${s}${n}`
    if (!seen.has(name)) {
      seen.add(name)
      names.push(name)
    }
  }
  return names
}

